// ---- THE GREAT WREATH — the level's signature: an AvalancheBall in festival dress. The snow sphere shrinks
// to a 0.4-scale core hub and a great evergreen TORUS (world radius ~1.12, tube 0.42 — outer edge ~1.54 vs
// physics r 1.4, slight visual over-read, never under) rolls around it with holly berries, gilt studs and a
// bow that goes round and round (festival physics). Physics and counters UNCHANGED: double-jump the crown,
// spin/pound shatters it (needles + berries + candy), stomp = the springboard ride. The base's stomp-squash
// wrote ball.scale.y directly (it would fight the 0.4 core), so the squash is re-owned here via _sq and the
// core scale is re-asserted each frame after super.update's damp. Grounded-bite assist carried over from
// w7l4: base touchPlayer measures against the ball's CENTER (gh+1.4), which a grounded Pip's 1.25 top never
// reaches — without it, standing in the wreath's path would be accidentally safe and the level would lie. ----
class GreatWreath extends AvalancheBall {
  constructor(G, x, y, opts={}){
    super(G, x, y, opts);
    // strip the base's 7 pressed-pebble flecks (draw-call budget: up to ~8 wreaths live at once) and shrink
    // the snow sphere to the core hub
    for(let i=this.ball.children.length-1;i>=0;i--) this.ball.remove(this.ball.children[i]);
    this.ball.scale.setScalar(0.4);
    this._sq = 1;
    const k = 1/0.4;                                 // children of the 0.4-scaled ball are sized x2.5 to compensate
    const ring = mesh('tor',[this.r*0.8*k, this.r*0.3*k, 8, 20], emat(0x2a5c40, 0x1a3c2c, 0.3));
    this.ball.add(ring);                             // child of the ball → inherits the roll rotation
    for(let i=0;i<6;i++){ const a=i/6*TAU; const cc=i%2?W9PAL.ornR:W9PAL.ornG;
      const berry=mesh('sph',[0.14*k,5,4], emat(cc,cc,0.7));
      berry.position.set(Math.cos(a)*this.r*0.8*k, Math.sin(a)*this.r*0.8*k, 0.26*k); this.ball.add(berry); }
    const bow=new THREE.Group();                     // the bow rides the rim — it goes around; nobody minds
    for(const s of [-1,1]){ const loop=mesh('sph',[0.18*k,6,5], emat(W9PAL.ornR,0x8a1e2c,0.4));
      loop.scale.set(1.5,0.75,0.5); loop.position.set(s*0.2*k,0.06*k,0.05*k); bow.add(loop); }
    const knot=mesh('sph',[0.1*k,5,4], mat(0x8a1e2c)); bow.add(knot);
    bow.position.set(0, -this.r*0.8*k, 0.2*k);
    this.ball.add(bow);
  }
  takeHit(player, kind){
    if(this.dead) return;
    if(kind==='stomp'){                              // the crown is a springboard, not a weak point (base law)
      AUDIO.stomp && AUDIO.stomp();
      this._sq = 0.78;                               // the wreath's own soft squash; update eases it back
      return;
    }
    this.die();                                      // the TIMELY HIT — needles and berries everywhere
  }
  die(){
    if(this.dead) return;
    const p=this.group.position;
    this.G.fx.spawn(new THREE.Vector3(p.x,p.y,p.z), 0x2a5c40, 12, {speed:4, life:0.5});   // pine needles
    this.G.fx.spawn(new THREE.Vector3(p.x,p.y,p.z), W9PAL.ornR, 8, {speed:3, life:0.5});  // holly berries
    super.die();                                     // Enemy.die pays the candy (0 at a lane's end — pure spectacle)
  }
  update(dt){
    super.update(dt);
    if(this.dead) return;
    this._sq = damp(this._sq, 1, 8, dt);
    this.ball.scale.set(0.4, 0.4*this._sq, 0.4);     // undo the base's y-damp toward 1 — the core stays a core
    // grounded-bite assist (w7l4 precedent — see the class header). FLEET-AUDIT FIX: both sibling guards
    // restored — never bite while FALLING (a wreath sailing overhead tagged idle players below, repro'd on
    // the 5s clock), and never bite a player ABOVE the wreath's center (the stomp-ride must stay safe).
    const pl=this.G.player, p=this.group.position;
    if(this.touchDamage && !this.falling && pl && !pl.dead && pl.grounded && pl.pos.y < p.y && Math.abs(pl.pos.z) < 1.3 &&
       Math.abs(pl.pos.x - p.x) < this.r*0.9 + 0.35){
      pl.damage(1, new THREE.Vector3(p.x + (pl.pos.x >= p.x ? -0.4 : 0.4), pl.pos.y, 0));
    }
  }
}
// ---- THE WINDER'S MOUTH — same fixed release clock as AvalancheSpawner, but it spawns GreatWreaths and its
// release voice is a BELL-JINGLE, not a landslide WHUMP (the brief's one override): count your five seconds
// by the sleigh-bell. ----
class GreatWreathSpawner extends AvalancheSpawner {
  update(dt, G){
    this.t += dt;
    if(this.t >= this.nextAt){
      this.nextAt += this.period;
      G.ents.add(new GreatWreath(G, this.x, this.y, this.o));
      G.fx.spawn(new THREE.Vector3(this.x, this.y+1.2, 0), 0x3aa060, 6, {speed:2, life:0.4});
      AUDIO.tone && AUDIO.tone({f:1568, f2:1046, type:'sine', t:0.22, vol:0.11});   // the bell — two bright partials
      AUDIO.tone && AUDIO.tone({f:2093, f2:1568, type:'sine', t:0.14, vol:0.07});
    }
  }
}

