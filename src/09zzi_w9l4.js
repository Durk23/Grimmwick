function updateW9L4(G, dt){
  updateLevelCommon(G, dt);
  const L4 = G._l94; if(!L4 || L4.area !== G.area) return;
  // ---- the landing telegraphs: each mouth's gilt floor-glow grows through the last 0.7s before its bell
  // (read straight off the spawner clocks — perfectly synced, no parallel timer to drift) and holds while
  // its wreath falls. Falling wreaths are matched to their mouth by roll direction + x-window (the two mid
  // mouths share a release moment but split cleanly on dir). w7l4 disc precedent, w9's warning gold. ----
  const hot = [false, false, false, false];
  for(const e of G.ents.list){
    if(e.dead || !e.isEnemy || e.constructor.name !== 'GreatWreath' || !e.falling) continue;
    const bx = e.group.position.x;
    for(let i=0;i<L4.drops.length;i++){
      const D = L4.drops[i];
      if(e.dir === D.dir && Math.abs(bx - D.cx) < 2.3) hot[i] = true;
    }
  }
  for(let i=0;i<L4.drops.length;i++){
    const D = L4.drops[i];
    const warn = (D.sp.nextAt - D.sp.t) < 0.7;
    const h = warn || hot[i];
    const m = D.disc.material;
    m.opacity = h ? Math.min(0.5, m.opacity + dt*2.2) : Math.max(0, m.opacity - dt*3);
    if(h) D.disc.scale.setScalar(0.6 + m.opacity*0.9 + Math.sin(G.time*22)*0.06);
  }
}

