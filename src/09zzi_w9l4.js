// an overhead garland bar between two trunks, hung with DECOY baubles at the spider's exact disguise spec
// (wire + r0.34 ball + gilt cap). Baked dead-still — the real spider sways a breath (its 'hang' idle); the
// stillness IS the 1% observation tell, and the rattle+0.6s unfold stays the honest telegraph either way.
function w9l4Garland(x1, x2, y, decoyXs){
  const g=new THREE.Group();
  const segs=Math.max(6, Math.floor((x2-x1)*1.2));
  let px=x1, py=y;
  for(let i=1;i<=segs;i++){
    const t=i/segs, qx=lerp(x1,x2,t), qy=y-Math.sin(t*Math.PI)*0.7;
    const len=Math.hypot(qx-px,qy-py);
    const seg=mesh('cyl',[0.05,0.05,len,4], mat(0x1e4030)); seg.position.set((px+qx)/2,(py+qy)/2,-0.5);
    seg.rotation.z=Math.atan2(qx-px,qy-py)*-1+Math.PI; g.add(seg);
    px=qx; py=qy;
  }
  for(const dx of decoyXs){
    const t=(dx-x1)/(x2-x1), gy=y-Math.sin(t*Math.PI)*0.7;
    const wire=mesh('cyl',[0.015,0.015,gy-4.4+0.6,4], mat(0x8a8f9a)); wire.position.set(dx,(gy+4.4)/2+0.1,0); g.add(wire);
    const cc=pick([W9PAL.ornR,W9PAL.ornE,0x7ae8ff]);
    const ball=mesh('sph',[0.34,9,8], emat(cc,cc,0.35)); ball.position.set(dx,4.4,0); g.add(ball);
    const capD=mesh('cyl',[0.1,0.12,0.12,8], mat(0xc9a24a)); capD.position.set(dx,4.78,0); g.add(capD);
  }
  return g;
}

