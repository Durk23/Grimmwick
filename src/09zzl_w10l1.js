// ---- terrace: a monumental stair block (mesh from y-1.2 to topY + bright ice lip + one AABB) ----
function w10l1Terrace(G, x1, x2, topY, color){
  const c = color||W10PAL.iceD;
  const w = x2-x1, cx = (x1+x2)/2, h = topY+1.2;
  const body = mesh('box',[w,h,10], mat(c)); body.position.set(cx, topY-h/2, 0);
  const lip = mesh('box',[w,0.14,10.25], mat(new THREE.Color(c).multiplyScalar(1.35).getHex()));
  lip.position.set(cx, topY+0.02, 0);
  G.scene.add(body, lip);
  G.world.addBox(cx, -1.2, 0, w, h, 10, {});
}
// ---- court notice board: the palace's gilt-trimmed formal signage (signPost bakes y0 — this one takes y) ----
function w10l1Sign(G, x, y, z, ry, text){
  const g = new THREE.Group();
  const pole = mesh('cyl',[0.07,0.09,1.4,5], mat(W10PAL.wall)); pole.position.y=0.7;
  const board = mesh('box',[1.5,0.8,0.1], mat(W10PAL.regalS)); board.position.y=1.5;
  const trim = mesh('box',[1.58,0.08,0.12], mat(W10PAL.regalG)); trim.position.y=1.92;
  g.add(pole,board,trim);
  g.position.set(x,y,z); g.rotation.y=ry;
  G.scene.add(g);
  G.signs.push({x,z,text});
}
// ---- velvet-runner climb: a hanging court tapestry (climb volume + visible runner + gilt rod) ----
function w10l1Runner(G, deco, x, y0, y1){
  const rod = mesh('cyl',[0.05,0.05,1.3,6], mat(W10PAL.regalG)); rod.rotation.x=Math.PI/2; rod.position.set(x, y1+0.12, 0); deco.add(rod);
  const cloth = mesh('box',[0.72,(y1-y0),0.06], mat(W10PAL.velvet)); cloth.position.set(x, (y0+y1)/2, -0.12); deco.add(cloth);
  const hem = mesh('box',[0.76,0.1,0.1], mat(W10PAL.regalG)); hem.position.set(x, y0+0.05, -0.12); deco.add(hem);
  for(const s of [-1,1]){ const tassel = mesh('cone',[0.05,0.18,5], mat(W10PAL.regalG)); tassel.position.set(x+s*0.3, y0-0.06, -0.12); tassel.rotation.x=Math.PI; deco.add(tassel); }
  G.world.addBox(x, y0, 0, 0.9, y1-y0, 1.2, {type:'climb'});
}
// ---- THE QUIET PROP builder: the guest-list stand (all baked; the ache is in the geometry) ----
function w10l1GuestList(x, z){
  const g = new THREE.Group();
  const plinth = mesh('cyl',[0.34,0.42,1.0,8], mat(W10PAL.regalS)); plinth.position.set(x,0.5,z); g.add(plinth);
  const desk = mesh('box',[0.9,0.08,0.7], mat(W10PAL.regalS)); desk.position.set(x,1.06,z); desk.rotation.x=-0.28; g.add(desk);
  // the open ledger — ten thousand pages, all of them white
  for(const s of [-1,1]){ const page = mesh('box',[0.4,0.05,0.56], mat(0xeef4ff)); page.position.set(x+s*0.21,1.15,z); page.rotation.x=-0.28; page.rotation.z=s*0.06; g.add(page); }
  const spine = mesh('box',[0.06,0.07,0.58], mat(W10PAL.velvetD)); spine.position.set(x,1.14,z); spine.rotation.x=-0.28; g.add(spine);
  // the first line of the first page — one careful gilt stroke: "maybe this year."
  const line = mesh('box',[0.26,0.012,0.03], emat(W10PAL.regalG, W10PAL.regalG, 0.5)); line.position.set(x-0.2,1.2,z-0.2); line.rotation.x=-0.28; g.add(line);
  // the centuries' stack beside the stand — every blank book, kept ready, kept neat
  for(let i=0;i<9;i++){
    const book = mesh('box',[0.56,0.09,0.42], mat(i%2?W10PAL.velvet:0x2a3450));
    book.position.set(x+0.95, 0.05+i*0.095, z+0.1); book.rotation.y = rand(-0.12,0.12); g.add(book);
  }
  const candle = mesh('cyl',[0.045,0.055,0.3,6], mat(W10PAL.regalS)); candle.position.set(x+0.3,1.28,z+0.18); candle.rotation.x=-0.28; g.add(candle);
  const flame = mesh('sph',[0.05,5,4], emat(0x7ae8ff,0x7ae8ff,0.9)); flame.position.set(x+0.3,1.46,z+0.13); g.add(flame);   // burning COLD, still lit
  return g;
}

